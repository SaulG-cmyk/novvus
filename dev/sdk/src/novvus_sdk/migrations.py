"""Migration generation (docs/MODULE_CONTRACT.md §5, docs/MULTITENANCY.md §2).

The canonical artifact is versioned SQL (`migrations/NNNN_name.sql`) that the
KERNEL executes inside the module schema with the restricted role. This
module generates those files:

- First migration: full DDL from the model metadata + the RLS policy block
  for every table + the `_processed_events` idempotency table.
- Subsequent migrations: Alembic autogenerate diff against a development
  database (NOVVUS_DATABASE_URL), rendered as offline SQL.
"""

from __future__ import annotations

import io
import re
from pathlib import Path
from typing import Any, cast

from alembic.autogenerate import produce_migrations
from alembic.migration import MigrationContext
from alembic.operations import Operations
from alembic.operations.ops import CreateTableOp, ModifyTableOps
from sqlalchemy import Table, create_engine, text
from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable

from novvus_sdk.app import NovvusModule
from novvus_sdk.events import PROCESSED_EVENTS_DDL

VERSION_RE = re.compile(r"^(\d{4})_([a-z0-9_]+)\.sql$")


def rls_block(table_name: str) -> str:
    """The exact RLS policy defined in docs/MULTITENANCY.md §2."""
    return (
        f"ALTER TABLE {table_name} ENABLE ROW LEVEL SECURITY;\n"
        f"ALTER TABLE {table_name} FORCE ROW LEVEL SECURITY;\n"
        f"CREATE POLICY tenant_isolation ON {table_name}\n"
        f"    USING (org_id = current_setting('app.org_id')::uuid)\n"
        f"    WITH CHECK (org_id = current_setting('app.org_id')::uuid);"
    )


def existing_versions(migrations_dir: Path) -> list[str]:
    if not migrations_dir.is_dir():
        return []
    return sorted(p.name for p in migrations_dir.glob("*.sql") if VERSION_RE.match(p.name))


def next_version(migrations_dir: Path, name: str) -> str:
    slug = re.sub(r"[^a-z0-9_]+", "_", name.lower()).strip("_") or "migration"
    versions = existing_versions(migrations_dir)
    number = 1
    if versions:
        last = VERSION_RE.match(versions[-1])
        assert last is not None
        number = int(last.group(1)) + 1
    return f"{number:04d}_{slug}"


def generate_initial_sql(module: NovvusModule) -> str:
    """Full DDL for every registered model, with RLS on each table."""
    dialect = postgresql.dialect()  # type: ignore[no-untyped-call]
    statements: list[str] = [
        f"-- {module.id} 0001: initial schema (generated by novvus-sdk)",
    ]
    tables = [cast(Table, model.__table__) for model in module.models]
    if not tables:
        raise ValueError("the module declares no models; nothing to generate")

    for table in tables:
        ddl = str(CreateTable(table).compile(dialect=dialect)).strip()
        statements.append(f"{ddl};")
        for index in table.indexes:
            index_ddl = str(CreateIndex(index).compile(dialect=dialect)).strip()
            statements.append(f"{index_ddl};")
        statements.append(rls_block(table.name))

    statements.append("-- idempotent event consumption (docs/EVENTS.md §4)")
    statements.append(PROCESSED_EVENTS_DDL)
    return "\n\n".join(statements) + "\n"


def generate_diff_sql(module: NovvusModule, dev_database_url: str) -> str:
    """Alembic autogenerate diff between the dev database (current applied
    state of the module schema) and the model metadata, as offline SQL."""
    if not module.models:
        raise ValueError("the module declares no models")
    metadata = module.models[0].metadata

    def include_object(obj: Any, name: str | None, type_: str, *_: Any) -> bool:
        return not (type_ == "table" and name == "_processed_events")

    sync_dsn = dev_database_url
    for prefix in ("postgresql+psycopg://", "postgresql://", "postgres://"):
        if sync_dsn.startswith(prefix):
            sync_dsn = "postgresql+psycopg://" + sync_dsn.removeprefix(prefix)
            break

    engine = create_engine(sync_dsn)
    try:
        with engine.connect() as conn:
            conn.execute(text(f"SET search_path = {module.schema}"))
            context = MigrationContext.configure(
                conn,
                opts={"target_metadata": metadata, "include_object": include_object},
            )
            script = produce_migrations(context, metadata)
    finally:
        engine.dispose()

    upgrade_ops = script.upgrade_ops
    if upgrade_ops is None or not upgrade_ops.ops:
        return ""

    buffer = io.StringIO()
    offline = MigrationContext.configure(
        url=sync_dsn,
        opts={"as_sql": True, "output_buffer": buffer, "target_metadata": metadata},
    )
    operations = Operations(offline)
    new_tables: list[str] = []
    flat: list[Any] = []
    for op in upgrade_ops.ops:
        if isinstance(op, ModifyTableOps):
            flat.extend(op.ops)
        else:
            flat.append(op)
    for op in flat:
        if isinstance(op, CreateTableOp):
            new_tables.append(op.table_name)
        operations.invoke(op)

    sql = buffer.getvalue()
    for table in new_tables:
        sql += "\n" + rls_block(table) + "\n"
    return sql


def makemigration(module: NovvusModule, name: str, dev_database_url: str | None) -> Path | None:
    """Write the next migration file; returns None when there is no change."""
    migrations_dir = module.root / "migrations"
    migrations_dir.mkdir(exist_ok=True)

    if not existing_versions(migrations_dir):
        sql = generate_initial_sql(module)
        version = f"0001_{re.sub(r'[^a-z0-9_]+', '_', name.lower()).strip('_') or 'init'}"
    else:
        if not dev_database_url:
            raise RuntimeError(
                "incremental migrations need NOVVUS_DATABASE_URL pointing at a dev database "
                "with the current module schema applied"
            )
        sql = generate_diff_sql(module, dev_database_url)
        if not sql.strip():
            return None
        version = next_version(migrations_dir, name)

    path = migrations_dir / f"{version}.sql"
    path.write_text(sql, encoding="utf-8", newline="\n")
    return path


def load_migration_sources(module_root: Path) -> list[dict[str, str]]:
    """Read migrations/*.sql as the payload for kernel registration."""
    migrations_dir = module_root / "migrations"
    sources = []
    for file_name in existing_versions(migrations_dir):
        match = VERSION_RE.match(file_name)
        assert match is not None
        sources.append(
            {
                "version": f"{match.group(1)}_{match.group(2)}",
                "sql": (migrations_dir / file_name).read_text(encoding="utf-8"),
            }
        )
    return sources
